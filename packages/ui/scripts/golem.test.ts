import { expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync, symlinkSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { createElement } from "react";
import { renderToString } from "react-dom/server";
import * as Onyx from "@mroiban/onyx";
import * as Golem from "@mroiban/golem";
import golem from "@mroiban/golem/package.json" with { type: "json" };
import * as UI from "../src";

const root = `${import.meta.dir}/..`;

test("motion-enabled controls replace Onyx's by name; everything else is Onyx's own", () => {
  for (const name of ["Switch", "Button", "Checkbox", "Toggle", "ToggleGroup", "TabsList", "Progress", "Meter", "Slider", "ToastProvider"] as const)
    expect(UI[name], name).toBe(Golem[name] as never);
  expect(UI.Switch).not.toBe(Onyx.Switch);
  // Shared contexts must be one instance: Golem's ToastProvider with Onyx's useToast.
  expect(UI.useToast).toBe(Onyx.useToast);
  expect(UI.Tabs).toBe(Onyx.Tabs);
  expect(renderToString(createElement(UI.Switch, { "aria-label": "Sync" }))).toContain('data-golem-part="switch"');
});

test("the Anima runtime path carries the installed Golem's version", () => {
  expect(UI.animaPath).toBe(`/_bedrock/anima/${golem.version}/`);
});

test("a pebble bundle that imports one control keeps the runtime configuration", async () => {
  const dir = mkdtempSync(join(tmpdir(), "bedrock-ui-golem-"));
  try {
    // By package name, as pebbles import it: only then does the bundler apply package.json sideEffects.
    mkdirSync(join(dir, "node_modules/@bedrock"), { recursive: true });
    symlinkSync(resolve(root), join(dir, "node_modules/@bedrock/ui"), "dir");
    await Bun.write(join(dir, "app.tsx"), `import { Switch } from "@bedrock/ui";\nexport const app = <Switch aria-label="x" />;\n`);
    const out = await Bun.build({ entrypoints: [join(dir, "app.tsx")], target: "browser", minify: true, external: ["react", "react-dom", "react/jsx-runtime"] });
    expect(out.success).toBe(true);
    const code = (await Promise.all(out.outputs.map(o => o.text()))).join("\n");
    // The call that points Golem at the runtime survives tree-shaking (src/golem.ts is in sideEffects);
    // the version is joined in at run time, as animaPath's own test checks.
    expect(code).toContain("/_bedrock/anima/");
    expect(code).toMatch(/runtime:`\$\{\w+\}anima\.js`/);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test("the stylesheet carries Golem's motion-part styles and Anima colour slots, but no Golem themes", async () => {
  const css = await Bun.file(`${root}/dist/styles.css`).text();
  expect(css).toContain(".golem-switch");
  expect(css).toContain("--anima-buttonBg: var(--onyx-control-button-bg)");
  // Golem's tokens.css (its own themes) stays out, and nothing appended redefines an Onyx token:
  // pebbles keep their colours.
  expect(css).not.toContain("Generated by @mroiban/golem from packages/golem/src/tokens/source.ts");
  for (const file of ["@mroiban/golem/anima-slots.css", "@mroiban/golem/styles.css"])
    expect(await Bun.file(Bun.resolveSync(file, root)).text(), file).not.toMatch(/--onyx-[\w-]+\s*:/);
  expect(css.indexOf(".golem-switch")).toBeGreaterThan(css.indexOf(".onyx-switch"));
});
