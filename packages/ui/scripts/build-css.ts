import { resolve, join } from "node:path";

const root = resolve(import.meta.dir, "..");
// Onyx ships a standalone stylesheet with its icon font inlined; Bedrock only appends its layouts.
export async function buildCss() {
  const onyx = await Bun.file(Bun.resolveSync("@mroiban/onyx/styles.css", root)).text();
  const bedrock = await Bun.file(join(root, "src/bedrock/styles.css")).text();
  const css = `/* Generated by bun run build:css. Do not edit.
 * Includes Onyx (MIT, https://github.com/MRoiban/onyx) and the Codicon font by
 * Microsoft (CC BY 4.0, https://github.com/microsoft/vscode-codicons). */\n${onyx}\n${bedrock}`;
  await Bun.write(join(root, "dist/styles.css"), css);
  return css;
}
if (import.meta.main) await buildCss();
