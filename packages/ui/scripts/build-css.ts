import { resolve, join } from "node:path";

const root = resolve(import.meta.dir, "..");
// Onyx ships a standalone stylesheet with its icon font inlined; Bedrock appends Golem's motion-part
// styles (they only read Onyx's tokens, so no theme changes) and its own layouts.
export async function buildCss() {
  const read = (specifier: string) => Bun.file(Bun.resolveSync(specifier, root)).text();
  const onyx = await read("@mroiban/onyx/styles.css");
  const golem = `${await read("@mroiban/golem/anima-slots.css")}\n${await read("@mroiban/golem/styles.css")}`;
  const bedrock = await Bun.file(join(root, "src/bedrock/styles.css")).text();
  const css = `/* Generated by bun run build:css. Do not edit.
 * Includes Onyx (MIT, https://github.com/MRoiban/onyx), Golem (MIT, https://github.com/MRoiban/golem)
 * and the Codicon font by Microsoft (CC BY 4.0, https://github.com/microsoft/vscode-codicons). */\n${onyx}\n${golem}\n${bedrock}`;
  await Bun.write(join(root, "dist/styles.css"), css);
  return css;
}
if (import.meta.main) await buildCss();
